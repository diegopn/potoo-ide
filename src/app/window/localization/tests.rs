#[cfg(test)]
pub(in crate::app::window) fn translate_known_text(
    from: UiLanguage,
    to: UiLanguage,
    text: &str,
) -> Option<String> {
    UI_TRANSLATION_KEYS
        .iter()
        .find_map(|key| (tr(from, key) == text).then(|| tr(to, key).to_string()))
}
